function buildSheetDetail(name: string, rows: Record<string, any>[]): SheetDetail {
  const columns = rows.length > 0 ? Object.keys(rows[0]) : [];
  const columnInfos: ColumnInfo[] = columns.map((col) => ({
    name: col,
    detectedMode: detectColumnMode(col),
    sampleValues: rows.slice(0, 3).map((r) => String(r[col] || '')),
  }));

  return {
    name,
    columns,
    columnInfos,
    rows,
  };
}

export function generateSampleWorkbook(): ExcelWorkbookData {
  const sheets: Record<string, SheetDetail> = {
    'Merchant Registration Repo': buildSheetDetail('Merchant Registration Repo', SAMPLE_MERCHANT_REGISTRATION_ROWS),
    'Employees_Staff': buildSheetDetail('Employees_Staff', SAMPLE_EMPLOYEE_ROWS),
    'Customer_Directory': buildSheetDetail('Customer_Directory', SAMPLE_CUSTOMER_ROWS),
    'Agent_Partners': buildSheetDetail('Agent_Partners', SAMPLE_PARTNER_ROWS),
  };

  const sheetNames = Object.keys(sheets);

  return {
    fileName: 'MMQR_Merchant_Registrations_Sample.xlsx',
    sheetNames,
    activeSheetName: sheetNames[0],
    sheets,
  };
}
